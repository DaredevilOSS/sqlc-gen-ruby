# frozen_string_literal: true

require_relative 'code'
require_relative 'options'
require_relative 'plugin_pb'
require_relative 'catalog'
require_relative 'type_resolver'
require_relative 'row_layout'
require_relative 'method_gen'
require_relative 'drivers/pg'
require_relative 'drivers/mysql2'
require_relative 'drivers/sqlite3'

module SqlcGenRuby
  # Ruby port of CodeGenerator/CodeGenerator.cs, extended with models, enums, sqlc.embed, ...
  class Generator
    HEADER = "# frozen_string_literal: true\n\n# auto-generated by sqlc - do not edit"
    RBS_HEADER = '# auto-generated by sqlc - do not edit'
    MODELS_FILE = 'models'
    CONNECTION_FILE = 'connection'

    def generate(request)
      @options = Options.new(request.plugin_options)
      @driver = instantiate_driver
      @catalog = Catalog.new(request.catalog)
      @driver.catalog = @catalog
      @types = TypeResolver.new(@driver, @options)
      @layout = RowLayout.new(@driver, @catalog, @types)

      name_anonymous_params(request.queries)
      models = models_files
      connection = connection_files
      reject_reserved_query_names(request.queries)
      by_class = request.queries.group_by { |q| class_name_for(q.filename) }
      reject_colliding_files(by_class.keys)
      files = by_class.flat_map do |class_name, queries|
        generate_files(queries, class_name, with_models: !models.empty?, with_connection: !connection.empty?)
      end
      files.concat(models).concat(connection)
      files << gemfile(request.queries) if @options.generate_gemfile
      Plugin::GenerateResponse.new(files: files)
    end

    private

    # `ANY($1::BIGINT[])` and other expressions arrive without a name; use sqlc.arg('ids') to pick one.
    def name_anonymous_params(queries)
      queries.each do |query|
        query.params.each do |param|
          param.column.name = "param#{param.number}" if param.column.name.empty?
        end
      end
    end

    def instantiate_driver
      case @options.driver_name
      when 'mysql2' then Drivers::Mysql2.new
      when 'pg' then Drivers::Pg.new(prepared_statements: @options.prepared_statements)
      when 'sqlite3' then Drivers::Sqlite3.new
      else raise ArgumentError, "unknown driver: #{@options.driver_name}"
      end
    end

    def module_name = @options.module_name || "#{@driver.name}Codegen"

    # query.sql => QuerySql
    def class_name_for(filename)
      ext = File.extname(filename)
      raise ArgumentError, "query file #{filename} has no extension" if ext.empty?

      Code.constant_part(File.basename(filename, ext)) + Code.constant_part(ext[1..])
    end

    # user-queries.sql and user_queries.sql would both write user_queries_sql.rb
    def reject_colliding_files(class_names)
      class_names.group_by { |c| Code.snake_case(c) }.each do |base, names|
        raise ArgumentError, "query files #{names.join(' and ')} would both generate #{base}.rb" if names.size > 1
      end
    end

    # A query named Transaction or Initialize would silently replace the generated method of the same name.
    def reject_reserved_query_names(queries)
      generated = (@driver.class_methods + @driver.private_methods).flat_map do |code, _|
        code.scan(/^\s*def (?:self\.)?([a-z_][A-Za-z0-9_]*[?!]?)/).flatten
      end
      reserved = generated + %w[initialize slice_placeholders] + Code::RESERVED_ATTRS
      queries.each do |query|
        func = Code.snake_case(query.name)
        next unless reserved.include?(func)

        raise ArgumentError, "query #{query.name} would generate ##{func}, which the generated class already defines; " \
                             'rename the query'
      end
    end

    def generate_files(queries, class_name, with_models:, with_connection:)
      method_gen = MethodGen.new(@driver, @layout, @types, class_name)
      members = queries.flat_map { |q| query_members(q, method_gen) }
      klass = class_members(queries, method_gen)
      base = Code.snake_case(class_name)

      code_body = members.map(&:first) + [Code.block("class #{class_name}", klass.map(&:first).join("\n\n"))]
      requires = requires_for(queries, with_models, with_connection)
      code = "#{HEADER}\n#{requires}\n\n#{Code.block("module #{module_name}", code_body.join("\n\n"))}\n"
      files = [Plugin::File.new(name: "#{base}.rb", contents: code)]

      if @options.generate_types
        type_body = members.map(&:last).compact + [Code.block("class #{class_name}", klass.map(&:last).join("\n\n"))]
        types = "#{RBS_HEADER}\n#{Code.block("module #{module_name}", type_body.join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{base}.rbs", contents: types)
      end
      files
    end

    def requires_for(queries, with_models, with_connection)
      lines = (@driver.required_gems + @driver.extra_requires(queries, @options.ruby_version)).map { |g| "require '#{g}'" }
      lines << "require_relative '#{CONNECTION_FILE}'" if with_connection
      lines << "require_relative '#{MODELS_FILE}'" if with_models
      lines.join("\n")
    end

    # [[code, rbs_or_nil], ...] for the SQL constant, row class, and (for :copyfrom) the class of the copied rows.
    def query_members(query, method_gen)
      members = []
      unless query.cmd == ':copyfrom' # copied rows are written by generated code, there is no SQL constant to run
        members << [@driver.query_text_constant(query), "#{Code.sql_constant(query.name)}: String"]
      end
      members << dataclass("#{Code.upcase_first(query.name)}Row", row_pairs(query)) unless query.columns.empty?
      if query.cmd == ':copyfrom'
        pairs = method_gen.params(query).map { |p| [Code.attr_name(p.name), p.type] }
        members << dataclass("#{Code.upcase_first(query.name)}Args", pairs)
      end
      members
    end

    def row_pairs(query) = @layout.entries(query).map { |e| [e.attr, e.type] }

    # constructor / connect / transaction, one method per query, then the private helpers
    def class_members(queries, method_gen)
      members = @driver.class_methods.dup
      members.concat(queries.map { |q| [method_gen.code(q), method_gen.type(q)] })
      helpers = @driver.private_methods + method_gen.helper_methods(queries)
      unless helpers.empty?
        members << ["private\n\n#{helpers.map(&:first).join("\n\n")}", "private\n\n#{helpers.map(&:last).join("\n\n")}"]
      end
      members
    end

    # --- data classes (Data.define / Struct.new) ---

    def dataclass(name, pairs)
      dupes = pairs.map(&:first).tally.select { |_, n| n > 1 }.keys
      raise ArgumentError, "duplicate column names in #{name}: #{dupes.join(', ')}" unless dupes.empty?

      @options.ruby_version.immutable_data_supported? ? data_define(name, pairs) : new_struct(name, pairs)
    end

    def data_define(name, pairs)
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" })
      code = "class #{name} < Data.define(#{attrs})\nend"
      readers = Code.indent(pairs.map { |n, t| "attr_reader #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def initialize: (#{init_args}) -> void")
      [code, "class #{name}\n#{readers}\n#{init}\nend"]
    end

    def new_struct(name, pairs)
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" })
      code = "class #{name} < Struct.new(#{attrs})\nend"
      accessors = Code.indent(pairs.map { |n, t| "attr_accessor #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def self.new: (#{init_args}) -> #{name}")
      [code, "class #{name} < ::Struct\n#{accessors}\n#{init}\nend"]
    end

    # --- models.rb: one class per table + one module per enum ---

    def models_files
      members = @catalog.enum_modules.map { |name, vals| enum_module(name, vals) }
      @catalog.tables.each do |table|
        next if table.columns.empty?

        pairs = table.columns.map { |c| [Code.attr_name(c.name), @types.type(c, fallback: 'untyped')] }
        members << dataclass(table.model_name, pairs)
      end
      return [] if members.empty?

      code = "#{HEADER}\n\n#{Code.block("module #{module_name}", members.map(&:first).join("\n\n"))}\n"
      files = [Plugin::File.new(name: "#{MODELS_FILE}.rb", contents: code)]
      if @options.generate_types
        types = "#{RBS_HEADER}\n#{Code.block("module #{module_name}", members.map(&:last).join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{MODELS_FILE}.rbs", contents: types)
      end
      files
    end

    # connection.rb: helpers shared by the query classes of the driver (per-connection state, constants)
    def connection_files
      members = @driver.module_members
      return [] if members.empty?

      files = [Plugin::File.new(name: "#{CONNECTION_FILE}.rb",
                                contents: "#{HEADER}\n\n#{Code.block("module #{module_name}", members.map(&:first).join("\n\n"))}\n")]
      if @options.generate_types
        types = "#{RBS_HEADER}\n#{Code.block("module #{module_name}", members.map(&:last).join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{CONNECTION_FILE}.rbs", contents: types)
      end
      files
    end

    # module BioType; AUTOBIOGRAPHY = 'Autobiography'; ...; ALL = [...].freeze; end
    def enum_module(name, values)
      consts = unique_constants(values)
      code = consts.map { |const, value| "#{const} = #{quote(value)}" }
      code << "ALL = [#{consts.map(&:first).join(', ')}].freeze"
      rbs = consts.map { |const, _| "#{const}: String" }
      rbs << 'ALL: Array[String]'
      [Code.block("module #{name}", code.join("\n")), Code.block("module #{name}", rbs.join("\n"))]
    end

    # 'Memoir' (single quotes unless the value needs escaping)
    def quote(value) = value.match?(/['\\\n]/) ? value.inspect : "'#{value}'"

    def unique_constants(values)
      seen = Hash.new(0)
      values.map do |value|
        const = Code.constant_name(value)
        seen[const] += 1
        [seen[const] == 1 ? const : "#{const}_#{seen[const]}", value]
      end
    end

    def gemfile(queries)
      gems = (@driver.required_gems + @driver.extra_gems(queries)).uniq.map { |g| "gem '#{g}'" }.join("\n")
      Plugin::File.new(name: 'Gemfile', contents: "source 'https://rubygems.org'\n\n#{gems}")
    end
  end
end
