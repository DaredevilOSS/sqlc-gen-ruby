# frozen_string_literal: true

require_relative 'code'
require_relative 'options'
require_relative 'plugin_pb'
require_relative 'catalog'
require_relative 'type_resolver'
require_relative 'row_layout'
require_relative 'method_gen'
require_relative 'drivers/pg'
require_relative 'drivers/mysql2'
require_relative 'drivers/sqlite3'

module SqlcGenRuby
  # Ruby port of CodeGenerator/CodeGenerator.cs, extended with models, enums, sqlc.embed, ...
  class Generator
    AUTO_GENERATED = '# auto-generated by sqlc - do not edit'
    MODELS_FILE = 'models'

    def generate(request)
      @options = Options.new(request.plugin_options)
      @driver = instantiate_driver
      @catalog = Catalog.new(request.catalog)
      @driver.catalog = @catalog
      @types = TypeResolver.new(@driver, @options)
      @layout = RowLayout.new(@driver, @catalog, @types)
      @method_gen = MethodGen.new(@driver, @layout, @types)

      name_anonymous_params(request.queries)
      models = models_files
      files = request.queries.group_by { |q| class_name_for(q.filename) }.flat_map do |class_name, queries|
        generate_files(queries, class_name, with_models: !models.empty?)
      end
      files.concat(models)
      files << gemfile(request.queries) if @options.generate_gemfile
      Plugin::GenerateResponse.new(files: files)
    end

    private

    # `ANY($1::BIGINT[])` and other expressions arrive without a name; use sqlc.arg('ids') to pick one.
    def name_anonymous_params(queries)
      queries.each do |query|
        query.params.each do |param|
          param.column.name = "param#{param.number}" if param.column.name.empty?
        end
      end
    end

    def instantiate_driver
      case @options.driver_name
      when 'mysql2' then Drivers::Mysql2.new
      when 'pg' then Drivers::Pg.new
      when 'sqlite3' then Drivers::Sqlite3.new
      else raise ArgumentError, "unknown driver: #{@options.driver_name}"
      end
    end

    def module_name = "#{@driver.name}Codegen"

    # query.sql => QuerySql
    def class_name_for(filename)
      ext = File.extname(filename)
      raise ArgumentError, "query file #{filename} has no extension" if ext.empty?

      Code.upcase_first(File.basename(filename, ext)) + Code.upcase_first(ext[1..])
    end

    def generate_files(queries, class_name, with_models:)
      members = queries.flat_map { |q| query_members(q) }
      klass = class_members(queries)
      base = Code.snake_case(class_name)

      code_body = (members.map(&:first) + [Code.block("class #{class_name}", klass.map(&:first).join("\n\n"))])
      requires = requires_for(queries, with_models)
      code = "#{AUTO_GENERATED}\n#{requires}\n\n#{Code.block("module #{module_name}", code_body.join("\n\n"))}"
      files = [Plugin::File.new(name: "#{base}.rb", contents: code)]

      if @options.generate_types
        type_body = members.map(&:last).compact + [Code.block("class #{class_name}", klass.map(&:last).join("\n"))]
        types = "#{AUTO_GENERATED}\n#{Code.block("module #{module_name}", type_body.join("\n\n"))}"
        files << Plugin::File.new(name: "#{base}.rbs", contents: types)
      end
      files
    end

    def requires_for(queries, with_models)
      lines = (@driver.required_gems + @driver.extra_requires(queries)).map { |g| "require '#{g}'" }
      lines << "require_relative '#{MODELS_FILE}'" if with_models
      lines.join("\n")
    end

    # [[code, rbs_or_nil], ...] for the SQL constant, row class, and args class.
    def query_members(query)
      members = []
      unless query.cmd == ':copyfrom' # copied rows are written by generated code, there is no SQL constant to run
        members << [@driver.query_text_constant(query), "#{query.name}Sql: String"]
      end
      members << dataclass("#{Code.upcase_first(query.name)}Row", row_pairs(query)) unless query.columns.empty?
      unless query.params.empty?
        members << dataclass("#{Code.upcase_first(query.name)}Args", param_pairs(query))
      end
      members
    end

    def row_pairs(query) = @layout.entries(query).map { |e| [e.attr, e.type] }

    def param_pairs(query)
      query.params.map do |p|
        type = p.column.is_sqlc_slice ? @types.slice_type(p.column, query.name) : @types.type(p.column, query_name: query.name)
        [p.column.name, type]
      end
    end

    def class_members(queries)
      members = [[@driver.init_code, @driver.init_type],
                 [@driver.transaction_code, @driver.transaction_type]]
      members.concat(queries.map { |q| [@method_gen.code(q), @method_gen.type(q)] })
      helpers = @method_gen.helper_methods(queries)
      unless helpers.empty?
        members << ["private\n\n#{helpers.map(&:first).join("\n\n")}",
                    "\nprivate\n#{helpers.map(&:last).join("\n")}"]
      end
      members
    end

    # --- data classes (Data.define / Struct.new) ---

    def dataclass(name, pairs)
      dupes = pairs.map(&:first).tally.select { |_, n| n > 1 }.keys
      raise ArgumentError, "duplicate column names in #{name}: #{dupes.join(', ')}" unless dupes.empty?

      @options.ruby_version.immutable_data_supported? ? data_define(name, pairs) : new_struct(name, pairs)
    end

    def data_define(name, pairs)
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" })
      code = "class #{name} < Data.define(#{attrs})\nend"
      readers = Code.indent(pairs.map { |n, t| "attr_reader #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def initialize: (#{init_args}) -> void")
      [code, "class #{name}\n#{readers}\n#{init}\nend"]
    end

    def new_struct(name, pairs)
      attrs = Code.comma_join(pairs.map(&:first))
      code = "class #{name} < Struct.new(#{attrs})\nend"
      accessors = Code.indent(pairs.map { |n, t| "attr_accessor #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def self.new: (#{init_args}) -> #{name}")
      [code, "class #{name} < ::Struct\n#{accessors}\n#{init}\nend"]
    end

    # --- models.rb: one class per table + one module per enum ---

    def models_files
      members = @catalog.enum_modules.map { |name, vals| enum_module(name, vals) }
      @catalog.tables.each do |table|
        next if table.columns.empty?

        pairs = table.columns.map { |c| [c.name, @types.type(c, fallback: 'untyped')] }
        members << dataclass(table.model_name, pairs)
      end
      return [] if members.empty?

      code = "#{AUTO_GENERATED}\n\n#{Code.block("module #{module_name}", members.map(&:first).join("\n\n"))}"
      files = [Plugin::File.new(name: "#{MODELS_FILE}.rb", contents: code)]
      if @options.generate_types
        types = "#{AUTO_GENERATED}\n#{Code.block("module #{module_name}", members.map(&:last).join("\n\n"))}"
        files << Plugin::File.new(name: "#{MODELS_FILE}.rbs", contents: types)
      end
      files
    end

    # module BioType; AUTOBIOGRAPHY = 'Autobiography'; ...; ALL = [...].freeze; end
    def enum_module(name, values)
      consts = unique_constants(values)
      code = consts.map { |const, value| "#{const} = #{value.inspect}" }
      code << "ALL = [#{consts.map(&:first).join(', ')}].freeze"
      rbs = consts.map { |const, _| "#{const}: String" }
      rbs << 'ALL: Array[String]'
      [Code.block("module #{name}", code.join("\n")), Code.block("module #{name}", rbs.join("\n"))]
    end

    def unique_constants(values)
      seen = Hash.new(0)
      values.map do |value|
        const = Code.constant_name(value)
        seen[const] += 1
        [seen[const] == 1 ? const : "#{const}_#{seen[const]}", value]
      end
    end

    def gemfile(queries)
      gems = (@driver.required_gems + @driver.extra_gems(queries)).uniq.map { |g| "gem '#{g}'" }.join("\n")
      Plugin::File.new(name: 'Gemfile', contents: "source 'https://rubygems.org'\n\n#{gems}")
    end
  end
end
