# frozen_string_literal: true

require_relative 'code'
require_relative 'options'
require_relative 'plugin_pb'
require_relative 'catalog'
require_relative 'type_resolver'
require_relative 'row_layout'
require_relative 'method_gen'
require_relative 'drivers/pg'
require_relative 'drivers/mysql2'
require_relative 'drivers/sqlite3'

module SqlcGenRuby
  # Ruby port of CodeGenerator/CodeGenerator.cs, extended with models, enums, sqlc.embed, ...
  class Generator
    HEADER = "# frozen_string_literal: true\n\n# auto-generated by sqlc - do not edit"
    RBS_HEADER = '# auto-generated by sqlc - do not edit'
    MODELS_FILE = 'models'
    CONNECTION_FILE = 'connection'

    def generate(request)
      @options = Options.new(request.plugin_options, request.global_options)
      check_engine(request.settings&.engine.to_s)
      @driver = instantiate_driver
      @catalog = Catalog.new(request.catalog, rename: @options.rename, exact_table_names: @options.exact_table_names)
      @driver.catalog = @catalog
      @types = TypeResolver.new(@driver, @options)
      @layout = RowLayout.new(@driver, @catalog, @types)

      name_anonymous_params(request.queries)
      check_constants(request.queries)
      models = models_files
      connection = connection_files
      by_class = request.queries.group_by { |q| class_name_for(q.filename) }
      reject_colliding_files(by_class)
      files = by_class.flat_map do |class_name, queries|
        generate_files(queries, class_name, with_models: !models.empty?, with_connection: !connection.empty?)
      end
      files.concat(models).concat(connection)
      files << gemfile(request.queries) if @options.generate_gemfile
      Plugin::GenerateResponse.new(files: files)
    end

    private

    # `ANY($1::BIGINT[])` and other expressions arrive without a name; use sqlc.arg('ids') to pick one.
    def name_anonymous_params(queries)
      queries.each do |query|
        query.params.each do |param|
          param.column.name = "param#{param.number}" if param.column.name.empty?
        end
      end
    end

    ENGINES = { 'pg' => 'postgresql', 'mysql2' => 'mysql', 'sqlite3' => 'sqlite' }.freeze

    def check_engine(engine)
      expected = ENGINES.fetch(@options.driver_name)
      return if engine.empty? || engine == expected

      raise ArgumentError, "driver #{@options.driver_name} needs engine: #{expected} (this sql block uses #{engine})"
    end

    # Everything is defined in one module: models, enums, query classes, rows, ... must not share a name.
    def check_constants(queries)
      names = @catalog.enum_modules.map { |name, _| [name, 'enum'] }
      names.concat(@catalog.tables.map { |t| [t.model_name, "model of table #{t.name}"] })
      queries.group_by { |q| class_name_for(q.filename) }.each do |class_name, list|
        names << [class_name, "query class of #{list.first.filename}"]
        list.each do |q|
          names << ["#{Code.upcase_first(q.name)}Row", "row class of query #{q.name}"] unless q.columns.empty?
          names << ["#{Code.upcase_first(q.name)}Args", "rows of query #{q.name}"] if q.cmd == ':copyfrom'
        end
      end
      names.concat(@driver.module_members.flat_map { |code, _| code.scan(/^(?:module|class) (\w+)|^(\w+) = /).flatten.compact }
                          .map { |n| [n, 'generated code'] })
      names.group_by(&:first).each do |name, uses|
        next if uses.size < 2

        raise ArgumentError, "#{module_name}::#{name} would be defined twice (#{uses.map(&:last).join(', ')}); " \
                             'rename one of them'
      end
    end

    def instantiate_driver
      case @options.driver_name
      when 'mysql2' then Drivers::Mysql2.new
      when 'pg' then Drivers::Pg.new(prepared_statements: @options.prepared_statements)
      when 'sqlite3' then Drivers::Sqlite3.new
      else raise ArgumentError, "unknown driver: #{@options.driver_name}"
      end
    end

    def module_name = @options.module_name || "#{@driver.name}Codegen"

    # query.sql => QuerySql
    def class_name_for(filename)
      ext = File.extname(filename)
      raise ArgumentError, "query file #{filename} has no extension" if ext.empty?

      Code.constant_part(File.basename(filename, ext)) + Code.constant_part(ext[1..])
    end

    # user-queries.sql and user_queries.sql would both be UserQueriesSql in user_queries_sql.rb
    def reject_colliding_files(by_class)
      by_class.group_by { |class_name, _| Code.snake_case(class_name) }.each do |base, classes|
        files = classes.flat_map { |_, queries| queries.map(&:filename) }.uniq
        raise ArgumentError, "query files #{files.join(' and ')} would both generate #{base}.rb" if files.size > 1
      end
    end

    def generate_files(queries, class_name, with_models:, with_connection:)
      method_gen = MethodGen.new(@driver, @layout, @types, "#{module_name}::#{class_name}")
      members = queries.flat_map { |q| query_members(q, method_gen) }
      klass = class_members(queries, method_gen)
      base = Code.snake_case(class_name)

      code_body = members.map(&:first) + [Code.block("class #{class_name}", klass.map(&:first).join("\n\n"))]
      requires = requires_for(queries, with_models, with_connection)
      code = "#{HEADER}\n#{requires}\n\n#{in_module(code_body.join("\n\n"))}\n"
      files = [Plugin::File.new(name: "#{base}.rb", contents: code)]

      if @options.generate_types
        type_body = members.map(&:last).compact + [Code.block("class #{class_name}", klass.map(&:last).join("\n\n"))]
        types = "#{RBS_HEADER}\n#{in_module(type_body.join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{base}.rbs", contents: types)
      end
      files
    end

    # module MyApp; module Db; ...; end; end (the parent modules do not need to exist)
    def in_module(body)
      module_name.split('::').reverse.reduce(body) { |inner, name| Code.block("module #{name}", inner) }
    end

    def requires_for(queries, with_models, with_connection)
      lines = (@driver.required_gems + @driver.extra_requires(queries, @options.ruby_version)).map { |g| "require '#{g}'" }
      lines << "require_relative '#{CONNECTION_FILE}'" if with_connection
      lines << "require_relative '#{MODELS_FILE}'" if with_models
      lines.join("\n")
    end

    # [[code, rbs_or_nil], ...] for the SQL constant, row class, and (for :copyfrom) the class of the copied rows.
    def query_members(query, method_gen)
      members = []
      unless query.cmd == ':copyfrom' # copied rows are written by generated code, there is no SQL constant to run
        members << [@driver.query_text_constant(query), "#{Code.sql_constant(query.name)}: ::String"]
      end
      members << dataclass("#{Code.upcase_first(query.name)}Row", row_pairs(query)) unless query.columns.empty?
      if MethodGen::ROWS_COMMANDS.include?(query.cmd)
        pairs = method_gen.params(query).reject(&:reused).map { |p| [p.name, p.type] }
        members << dataclass("#{Code.upcase_first(query.name)}Args", pairs)
      end
      members
    end

    def row_pairs(query) = @layout.entries(query).map { |e| [e.attr, e.type] }

    # constructor / connect / transaction, one method per query, then the private helpers
    def class_members(queries, method_gen)
      members = @driver.class_methods(@options.ruby_version).dup
      if queries.any? { |q| q.cmd == ':execresult' }
        # last_insert_id is nil on PostgreSQL (use RETURNING)
        members << dataclass('ExecResult', [%w[rows_affected ::Integer], ['last_insert_id', '::Integer?']])
      end
      helpers = @driver.private_methods(@options.ruby_version) + method_gen.helper_methods(queries)
      check_method_names(queries, (members + helpers).flat_map { |code, _| code.scan(/^def (?:self\.)?([\w?!]+)/) }.flatten +
                                  Code::OBJECT_METHODS)
      members.concat(queries.map { |q| [method_gen.code(q), method_gen.type(q)] })
      unless helpers.empty?
        members << ["private\n\n#{helpers.map(&:first).join("\n\n")}", "private\n\n#{helpers.map(&:last).join("\n\n")}"]
      end
      members
    end

    def check_method_names(queries, generated)
      taken = generated.to_h { |name| [name, 'a method of the generated class'] }
      Code::KERNEL_METHODS.each { |name| taken[name] = 'a Kernel method used by the generated class' }
      queries.each do |q|
        func = Code.snake_case(q.name)
        [func, *("#{func}!" if q.cmd == ':one')].each do |name|
          if taken.key?(name)
            raise ArgumentError, "query #{q.name}: method #{name} is already #{taken[name]}; rename the query"
          end

          taken[name] = "the method of query #{q.name}"
        end
      end
    end

    # --- data classes (Data.define / Struct.new) ---

    # doc: comment of the class (table comment), attr_docs: { attr => comment } (column comments, RBS only)
    def dataclass(name, pairs, doc: nil, attr_docs: {})
      dupes = pairs.map(&:first).tally.select { |_, n| n > 1 }.keys
      raise ArgumentError, "duplicate column names in #{name}: #{dupes.join(', ')}" unless dupes.empty?

      code, rbs = @options.ruby_version.immutable_data_supported? ? data_define(name, pairs, attr_docs) : new_struct(name, pairs, attr_docs)
      code = Code.without_cops(code, Code.naming_cops(attributes: pairs.map(&:first)))
      comment = Code.comment(doc)
      comment.empty? ? [code, rbs] : ["#{comment}\n#{code}", "#{comment}\n#{rbs}"]
    end

    def attribute_lines(pairs, attr_docs, keyword)
      pairs.map do |n, t|
        comment = Code.comment(attr_docs[n])
        line = "#{keyword} #{n}: #{t}"
        comment.empty? ? line : "#{comment}\n#{line}"
      end.join("\n")
    end

    def data_define(name, pairs, attr_docs = {})
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" })
      code = "class #{name} < ::Data.define(#{attrs})\nend"
      readers = Code.indent(attribute_lines(pairs, attr_docs, 'attr_reader'))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def initialize: (#{init_args}) -> void")
      [code, "class #{name}\n#{readers}\n#{init}\nend"]
    end

    # Ruby < 3.2: keyword_init so that rows are built like Data rows (`Row.new(id: 1, name: 'x')`).
    def new_struct(name, pairs, attr_docs = {})
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" } + ['keyword_init: true'])
      code = "#{name} = ::Struct.new(#{attrs})"
      accessors = Code.indent(attribute_lines(pairs, attr_docs, 'attr_accessor'))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{n}: #{t}" }))
      init = Code.indent("def initialize: (#{init_args}) -> void")
      new = Code.indent("def self.new: (#{init_args}) -> #{name}")
      [code, "class #{name} < ::Struct[untyped]\n#{accessors}\n#{init}\n#{new}\nend"]
    end

    # --- models.rb: one class per table + one module per enum ---

    def models_files
      members = @catalog.enum_modules.map { |name, vals, comment| enum_module(name, vals, comment) }
      @catalog.tables.each do |table|
        next if table.columns.empty?

        ident = Plugin::Identifier.new(schema: table.schema, name: table.name)
        pairs = table.columns.map { |c| [@types.member_name(@catalog.column_name(c.name)), @types.type(c, table: ident, fallback: 'untyped')] }
        docs = table.columns.to_h { |c| [@types.member_name(@catalog.column_name(c.name)), c.comment.to_s] }
        members << dataclass(table.model_name, pairs, doc: table.comment, attr_docs: docs)
      end
      return [] if members.empty?

      code = "#{HEADER}\n\n#{in_module(members.map(&:first).join("\n\n"))}\n"
      files = [Plugin::File.new(name: "#{MODELS_FILE}.rb", contents: code)]
      if @options.generate_types
        types = "#{RBS_HEADER}\n#{in_module(members.map(&:last).join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{MODELS_FILE}.rbs", contents: types)
      end
      files
    end

    # connection.rb: helpers shared by the query classes of the driver (per-connection state, constants)
    def connection_files
      members = @driver.module_members
      return [] if members.empty?

      files = [Plugin::File.new(name: "#{CONNECTION_FILE}.rb",
                                contents: "#{HEADER}\n\n#{in_module(members.map(&:first).join("\n\n"))}\n")]
      if @options.generate_types
        types = "#{RBS_HEADER}\n#{in_module(members.map(&:last).join("\n\n"))}\n"
        files << Plugin::File.new(name: "#{CONNECTION_FILE}.rbs", contents: types)
      end
      files
    end

    # module BioType; AUTOBIOGRAPHY = 'Autobiography'; ...; ALL = [...].freeze; end
    def enum_module(name, values, comment = nil)
      consts = unique_constants(values)
      code = consts.map { |const, value| "#{const} = #{quote(value)}" }
      code << "ALL = [#{consts.map(&:first).join(', ')}].freeze"
      rbs = consts.map { |const, _| "#{const}: ::String" }
      rbs << 'ALL: ::Array[::String]'
      doc = Code.comment(comment)
      doc = doc.empty? ? '' : "#{doc}\n"
      ["#{doc}#{Code.block("module #{name}", code.join("\n"))}", "#{doc}#{Code.block("module #{name}", rbs.join("\n"))}"]
    end

    # 'Memoir' (single quotes unless the value needs escaping)
    def quote(value) = value.match?(/['\\\n]/) ? value.inspect : "'#{value}'"

    def unique_constants(values)
      taken = {}
      values.map do |value|
        base = Code.constant_name(value)
        const = base
        suffix = 1
        const = "#{base}_#{suffix += 1}" while taken.key?(const)
        taken[const] = true
        [const, value]
      end
    end

    def gemfile(queries)
      gems = (@driver.required_gems + @driver.extra_gems(queries)).uniq.sort.map { |g| "gem '#{g}'" }
      gems << "gem 'timeout', '>= 0.4'" if @options.ruby_version < RubyVersion.new(3, 3)
      gems.sort!
      gems = gems.join("\n")
      Plugin::File.new(name: 'Gemfile', contents: "# frozen_string_literal: true\n\nsource 'https://rubygems.org'\n\n#{gems}\n")
    end
  end
end
