# frozen_string_literal: true

require_relative 'code'
require_relative 'options'
require_relative 'plugin_pb'
require_relative 'drivers/pg'

module SqlcGenRuby
  # Ruby port of CodeGenerator/CodeGenerator.cs + Drivers/MethodGen.cs.
  class Generator
    include Code

    AUTO_GENERATED = '# auto-generated by sqlc - do not edit'

    def generate(request)
      @options = Options.new(request.plugin_options)
      @driver = instantiate_driver
      files = request.queries.group_by { |q| class_name_for(q.filename) }.flat_map do |class_name, queries|
        generate_files(queries, class_name)
      end
      files << gemfile if @options.generate_gemfile
      Plugin::GenerateResponse.new(files: files)
    end

    private

    def instantiate_driver
      case @options.driver.downcase
      when 'pg' then Drivers::Pg.new
      else raise ArgumentError, "unknown or not-yet-ported driver: #{@options.driver}"
      end
    end

    # query.sql => QuerySql
    def class_name_for(filename)
      ext = File.extname(filename)
      Code.upcase_first(File.basename(filename, ext)) + Code.upcase_first(ext[1..])
    end

    def generate_files(queries, class_name)
      module_name = "#{@driver.name}Codegen"
      members = queries.flat_map { |q| query_members(q) }
      klass = class_members(queries)
      base = Code.snake_case(class_name)

      code_body = (members.map(&:first) + [Code.block("class #{class_name}", klass.map(&:first).join("\n\n"))])
      gems = @driver.required_gems.map { |g| "require '#{g}'" }.join("\n")
      code = "#{AUTO_GENERATED}\n#{gems}\n\n#{Code.block("module #{module_name}", code_body.join("\n\n"))}"
      files = [Plugin::File.new(name: "#{base}.rb", contents: code)]

      if @options.generate_types
        type_body = members.map(&:last).compact + [Code.block("class #{class_name}", klass.map(&:last).join("\n"))]
        types = "#{AUTO_GENERATED}\n#{Code.block("module #{module_name}", type_body.join("\n\n"))}"
        files << Plugin::File.new(name: "#{base}.rbs", contents: types)
      end
      files
    end

    # [[code, rbs_or_nil], ...] for the SQL constant, row class, and args class.
    def query_members(query)
      members = [[@driver.query_text_constant(query), "#{query.name}Sql: String"]]
      members << dataclass("#{Code.upcase_first(query.name)}Row", query.columns) unless query.columns.empty?
      unless query.params.empty?
        members << dataclass("#{Code.upcase_first(query.name)}Args", query.params.map(&:column))
      end
      members
    end

    def class_members(queries)
      [[@driver.init_code, @driver.init_type]] + queries.map { |q| [method_code(q), method_type(q)] }
    end

    def dataclass(name, columns)
      pairs = columns.map { |c| [c.name, @driver.column_type(c)] }
      @options.immutable_data_supported? ? data_define(name, pairs) : new_struct(name, pairs)
    end

    def data_define(name, pairs)
      attrs = Code.comma_join(pairs.map { |n, _| ":#{n}" })
      code = "class #{name} < Data.define(#{attrs})\nend"
      readers = Code.indent(pairs.map { |n, t| "attr_reader #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def initialize: (#{init_args}) -> void")
      [code, "class #{name}\n#{readers}\n#{init}\nend"]
    end

    def new_struct(name, pairs)
      attrs = Code.comma_join(pairs.map(&:first))
      code = "class #{name} < Struct.new(#{attrs})\nend"
      accessors = Code.indent(pairs.map { |n, t| "attr_accessor #{n}: #{t}" }.join("\n"))
      init_args = Code.indent(Code.comma_join(pairs.map { |n, t| "#{t} #{n}" }))
      init = Code.indent("def self.new: (#{init_args}) -> #{name}")
      [code, "class #{name} < ::Struct\n#{accessors}\n#{init}\nend"]
    end

    # --- methods (MethodGen) ---

    def method_code(query)
      func = Code.snake_case(query.name)
      const = "#{query.name}Sql"
      args_var = Code.snake_case("#{query.name}Args")
      has_params = !query.params.empty?
      lines = []
      if has_params
        list = Code.comma_join(query.params.map { |p| "#{args_var}.#{p.column.name}" })
        lines << "query_params = [#{list}]"
      end
      lines << @driver.prepare_stmt(func, const)
      exec = @driver.execute_stmt(func, has_params)

      case query.cmd
      when ':one'
        lines << "result = #{exec}"
        lines << 'row = result.first'
        lines << 'return nil if row.nil?'
        lines << "entity = #{new_row(query)}"
        lines << 'return entity'
      when ':many'
        lines << "result = #{exec}"
        lines << 'entities = []'
        lines << Code.block('result.each do |row|', "entities << #{new_row(query)}")
        lines << 'return entities'
      when ':exec'
        lines << exec
      else
        raise "unsupported query command: #{query.cmd}"
      end

      params = has_params ? "(#{args_var})" : ''
      Code.block("def #{func}#{params}", Code.block('@db.with do |client|', lines.join("\n")))
    end

    def new_row(query)
      args = Code.comma_join(query.columns.map { |c| "row['#{c.name}']" })
      "#{query.name}Row.new(#{args})"
    end

    def method_type(query)
      func = Code.snake_case(query.name)
      params = query.params.empty? ? '' : "(#{query.name}Args) "
      ret = query.cmd == ':one' ? "#{query.name}Row?" : 'void'
      "\ndef #{func}: #{params}-> #{ret}"
    end

    def gemfile
      gems = @driver.required_gems.map { |g| "gem '#{g}'" }.join("\n")
      Plugin::File.new(name: 'Gemfile', contents: "source 'https://rubygems.org'\n\n#{gems}")
    end
  end
end
